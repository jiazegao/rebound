/**
 * Generated visual bonuses: templates that draw a figure and ask a bonus question about it, for the
 * Visual lab and Finals-style scrimmages (NSB Finals visual bonuses have no official samples).
 *
 * A generated question's id is "vis-<template id>-<seed>". The template and the seed rebuild the same
 * figure, question and answer anywhere, so review cards, game logs and remote rooms only keep the id.
 */
import { SUBJECT_LABELS, type CoreSubject, type Question } from '../schema';
import { makeRng, newSeed } from './rng';
import { BIOLOGY_TEMPLATES } from './templates/biology';
import { CHEMISTRY_TEMPLATES } from './templates/chemistry';
import { EARTH_SPACE_TEMPLATES } from './templates/earth_space';
import { ENERGY_TEMPLATES } from './templates/energy';
import { MATH_TEMPLATES } from './templates/math';
import { PHYSICS_TEMPLATES } from './templates/physics';
import type { VisualDraft, VisualTemplate } from './types';

export type { VisualDraft, VisualTemplate } from './types';

export const VISUAL_TEMPLATES: VisualTemplate[] = [
  ...BIOLOGY_TEMPLATES,
  ...CHEMISTRY_TEMPLATES,
  ...EARTH_SPACE_TEMPLATES,
  ...ENERGY_TEMPLATES,
  ...MATH_TEMPLATES,
  ...PHYSICS_TEMPLATES,
];

const BY_ID = new Map(VISUAL_TEMPLATES.map((t) => [t.id, t]));

export function visualTemplate(id: string): VisualTemplate | undefined {
  return BY_ID.get(id);
}

export function templatesFor(subject: CoreSubject): VisualTemplate[] {
  return VISUAL_TEMPLATES.filter((t) => t.subject === subject);
}

/** Set id used for generated visual questions (in question sources and the seen ledger). */
export const GENERATED_SET_ID = 'vis';

export function generatedId(templateId: string, seed: number): string {
  return `vis-${templateId}-${seed}`;
}

export function parseGeneratedId(id: string): { templateId: string; seed: number } | null {
  const m = /^vis-(.+)-(\d+)$/.exec(id);
  if (!m) return null;
  const seed = Number(m[2]);
  return Number.isSafeInteger(seed) ? { templateId: m[1]!, seed } : null;
}

export function isGeneratedId(id: string): boolean {
  return parseGeneratedId(id) !== null;
}

/** The complete answer line, as a reader sees it. */
function answerLine(d: VisualDraft): string {
  const main = d.format === 'multiple_choice' && d.answerLetter ? `${d.answerLetter}) ${d.answer}` : d.answer;
  return d.accept?.length ? `${main} (ACCEPT: ${d.accept.join(', ')})` : main;
}

/** Turn a template's draft into a library-style question. */
export function draftToQuestion(template: VisualTemplate, seed: number, d: VisualDraft): Question {
  return {
    id: generatedId(template.id, seed),
    kind: 'bonus',
    number: 1,
    subject: template.subject,
    sourceCategory: SUBJECT_LABELS[template.subject].toUpperCase(),
    format: d.format,
    stem: d.stem,
    ...(d.choices ? { choices: d.choices, answerLetter: d.answerLetter } : {}),
    answer: d.answer,
    accept: d.accept ?? [],
    reject: d.reject ?? [],
    answerRaw: answerLine(d),
    visual: true,
    figure: { kind: 'svg', svg: d.svg, alt: d.alt },
    source: { provider: 'rebound', setId: GENERATED_SET_ID, roundId: template.id, credit: `Generated by Rebound (${template.title})` },
    ...(d.topic ? { topic: d.topic } : {}),
  };
}

/** The question a generated id stands for, or null if the template no longer exists. */
export function generateVisual(templateId: string, seed: number): Question | null {
  const template = BY_ID.get(templateId);
  if (!template) return null;
  return draftToQuestion(template, seed, template.make(makeRng(seed)));
}

export function questionForGeneratedId(id: string): Question | null {
  const parsed = parseGeneratedId(id);
  return parsed ? generateVisual(parsed.templateId, parsed.seed) : null;
}

/** A new generated question from one of `templates` (all of them by default). */
export function randomVisual(templates: VisualTemplate[] = VISUAL_TEMPLATES, random: () => number = Math.random): Question {
  if (templates.length === 0) throw new Error('No visual templates to choose from.');
  const template = templates[Math.floor(random() * templates.length)]!;
  const seed = newSeed(random);
  return draftToQuestion(template, seed, template.make(makeRng(seed)));
}
